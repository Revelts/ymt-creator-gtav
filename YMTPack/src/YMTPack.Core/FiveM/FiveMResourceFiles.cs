using System.Text;
using System.Xml.Linq;
using YMTPack.Core.Model;
using YMTPack.Core.Planning;

namespace YMTPack.Core.FiveM;

/// <summary>
/// ShopPedApparel .meta and fxmanifest.lua in the shape shown by the cfx.re tutorial
/// "How to stream clothes and props as addons for mp freemode models".
/// </summary>
public static class FiveMResourceFiles
{
    public const string ShopMetaDataFile = "SHOP_PED_APPAREL_META_FILE";

    public static string ShopMetaFileName(PedVariationPlan plan) => plan.FullName + ".meta";

    public static XDocument ShopPedApparel(PedVariationPlan plan)
    {
        ArgumentNullException.ThrowIfNull(plan);

        return new XDocument(
            new XDeclaration("1.0", "UTF-8", null),
            new XElement("ShopPedApparel",
                new XElement("pedName", plan.Gender.PedName()),
                new XElement("dlcName", plan.DlcName),
                new XElement("fullDlcName", plan.FullName),
                new XElement("eCharacter", plan.Gender.ShopCharacter()),
                new XElement("creatureMetaData", plan.HasCreatureMetadata ? plan.CreatureMetadataName : ""),
                new XElement("pedOutfits", ""),
                new XElement("pedComponents", ""),
                new XElement("pedProps", "")));
    }

    public static string FxManifest(IReadOnlyList<string> metaFileNames)
    {
        ArgumentNullException.ThrowIfNull(metaFileNames);

        var sb = new StringBuilder()
            .AppendLine("-- Generated by ymtpack")
            .AppendLine("fx_version 'cerulean'")
            .AppendLine("game 'gta5'")
            .AppendLine()
            .AppendLine("files {");
        foreach (string meta in metaFileNames)
        {
            sb.AppendLine($"    '{meta}',");
        }

        sb.AppendLine("}").AppendLine();
        foreach (string meta in metaFileNames)
        {
            sb.AppendLine($"data_file '{ShopMetaDataFile}' '{meta}'");
        }

        return sb.ToString();
    }
}
